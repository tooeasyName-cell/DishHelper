def system_prompt(scene: str, explain: bool, branch: bool) -> str:
    """Return deterministic instructions; no model is used to route a scene."""
    if scene not in SCENE_LABELS:
        raise ValueError(f"不支持的场景：{scene}")
    explanation = (
        "【解释模式】默认附上与当前操作有关的简短原理解释；保持实用，避免无关长篇。"
        if explain
        else "【解释模式】默认直接给出实用答案，不主动展开长篇原理；用户明确问为什么、原理或原因时，仍须回答该问题。"
    )
    branch_rule = (
        "【会话范围】这是独立临时分支，只依据本分支提供的资料回答和维护状态；不得声称读过主会话，或已将结论合并回主会话/本餐。"
        if branch
        else "【会话范围】只维护当前会话提供的状态。跨场景共享和分支管理由应用处理，不声称自行更新了其他会话。"
    )
    return "\n".join((_COMMON, _SCENES[scene], explanation, branch_rule))
